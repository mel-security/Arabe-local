// sql-writer.js — Accumulates SQL statements and writes them to a file
import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, '../output');

function esc(val) {
  if (val === null || val === undefined) return 'NULL';
  return `'${String(val).replace(/'/g, "''")}'`;
}

export class SqlWriter {
  constructor() {
    this._sections = {
      surahs: [],
      verses: [],
      letters: [],
      words: [],
    };
    this._timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  }

  addSurahInsert(s) {
    this._sections.surahs.push(
      `INSERT OR IGNORE INTO surahs (id, number, name_ar, name_fr, name_en, transliteration, revelation_type, verses_count, order_revealed) VALUES (${s.number}, ${s.number}, ${esc(s.name_ar)}, ${esc(s.name_fr)}, ${esc(s.name_en)}, ${esc(s.transliteration)}, ${esc(s.revelation_type)}, ${s.verses_count}, ${s.order_revealed ?? 'NULL'});`
    );
  }

  addVerseInsert(v) {
    this._sections.verses.push(
      `INSERT OR IGNORE INTO verses (surah_id, verse_number, arabic_text, translation_fr, translation_en, transliteration, audio_file, juz, page) VALUES (${v.surah_id}, ${v.verse_number}, ${esc(v.arabic_text)}, ${esc(v.translation_fr)}, ${esc(v.translation_en)}, NULL, ${esc(v.audio_file)}, ${v.juz ?? 'NULL'}, ${v.page ?? 'NULL'});`
    );
  }

  addVerseAudioUpdate(surahId, verseNumber, audioPath) {
    this._sections.verses.push(
      `UPDATE verses SET audio_file = ${esc(audioPath)} WHERE surah_id = ${surahId} AND verse_number = ${verseNumber};`
    );
  }

  addLetterUpdate(id, audioPath, imagePath) {
    this._sections.letters.push(
      `UPDATE letters SET audio_file = ${esc(audioPath)}, image_file = ${esc(imagePath)} WHERE id = ${id};`
    );
  }

  addWordUpdate(id, audioPath, imagePath) {
    const parts = [];
    if (audioPath !== undefined) parts.push(`audio_file = ${esc(audioPath)}`);
    if (imagePath !== undefined) parts.push(`image_file = ${esc(imagePath)}`);
    if (parts.length === 0) return;
    this._sections.words.push(
      `UPDATE vocabulary_words SET ${parts.join(', ')} WHERE id = ${id};`
    );
  }

  getSql() {
    const now = new Date().toISOString();
    const lines = [
      `-- Generated by data-fetcher on ${now}`,
      `-- Arabe Local — Asset DB seed`,
      `-- Apply with: sqlite3 arabe_local.db < updates.sql`,
      '',
      'BEGIN TRANSACTION;',
      '',
    ];

    if (this._sections.surahs.length > 0) {
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(`-- SURAHS (${this._sections.surahs.length} entrées)`);
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(...this._sections.surahs);
      lines.push('');
    }

    if (this._sections.verses.length > 0) {
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(`-- VERSETS (${this._sections.verses.length} opérations)`);
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(...this._sections.verses);
      lines.push('');
    }

    if (this._sections.letters.length > 0) {
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(`-- LETTRES (${this._sections.letters.length} mises à jour)`);
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(...this._sections.letters);
      lines.push('');
    }

    if (this._sections.words.length > 0) {
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(`-- MOTS (${this._sections.words.length} mises à jour)`);
      lines.push('-- ═══════════════════════════════════════════════');
      lines.push(...this._sections.words);
      lines.push('');
    }

    lines.push('COMMIT;');
    return lines.join('\n');
  }

  flush() {
    mkdirSync(OUTPUT_DIR, { recursive: true });
    const filename = resolve(OUTPUT_DIR, `updates-${this._timestamp}.sql`);
    writeFileSync(filename, this.getSql(), 'utf8');
    return filename;
  }

  totalStatements() {
    return Object.values(this._sections).reduce((sum, arr) => sum + arr.length, 0);
  }
}
